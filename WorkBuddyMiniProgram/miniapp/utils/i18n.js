/* 支持的语言列表（用于设置页与启动日志）。 */
var SUPPORTED = ['zh-CN', 'zh-TW', 'en', 'ja', 'fr', 'es', 'pt', 'ko', 'hi'];
var DEFAULT_LANG = 'zh-CN';

/* 简单事件总线：发布 / 订阅语言切换事件。 */
var listeners = [];

function onChange(cb) {
  if (typeof cb === 'function') listeners.push(cb);
}

function emitChange(prev, next) {
  for (var i = 0; i < listeners.length; i++) {
    try { listeners[i]({ prev: prev, next: next }); } catch (e) { /* ignore */ }
  }
}

/* i18n 单例状态 + 持久化。 */
var STATE = {
  lang: DEFAULT_LANG,
  loaded: false,
  storageKey: 'wb.i18n.lang'
};

function detectSystemLang() {
  try {
    var info = wx.getSystemInfoSync && wx.getSystemInfoSync();
    var raw = (info && info.language) || 'zh-CN';
    raw = String(raw).toLowerCase();
    if (raw.indexOf('zh') === 0) {
      if (raw === 'zh-tw' || raw === 'zh-hk' || raw === 'zh-mo') return 'zh-TW';
      return 'zh-CN';
    }
    if (raw.indexOf('ja') === 0) return 'ja';
    if (raw.indexOf('en') === 0) return 'en';
  } catch (e) { /* ignore */ }
  return DEFAULT_LANG;
}

function load() {
  if (STATE.loaded) return STATE.lang;
  try {
    var saved = wx.getStorageSync(STATE.storageKey);
    if (saved && SUPPORTED.indexOf(saved) >= 0) {
      STATE.lang = saved;
      STATE.loaded = true;
      return STATE.lang;
    }
  } catch (e) { /* ignore */ }
  STATE.lang = detectSystemLang();
  if (SUPPORTED.indexOf(STATE.lang) < 0) STATE.lang = DEFAULT_LANG;
  STATE.loaded = true;
  return STATE.lang;
}

function getLang() {
  if (!STATE.loaded) load();
  return STATE.lang;
}

function setLang(lang) {
  var prev = STATE.lang;
  var next = SUPPORTED.indexOf(lang) >= 0 ? lang : DEFAULT_LANG;
  STATE.lang = next;
  STATE.loaded = true;
  try { wx.setStorageSync(STATE.storageKey, next); } catch (e) { /* ignore */ }
  emitChange(prev, next);
  return next;
}

/** 取一个字符串；支持 {var} 占位符；缺失时回退到简体中文 → key。 */
function t(key, vars) {
  var lang = getLang();
  var dict = STRINGS[lang] || STRINGS[DEFAULT_LANG];
  var str = dict[key];
  if (str === undefined) str = STRINGS[DEFAULT_LANG][key];
  if (str === undefined) return key;
  if (!vars) return str;
  return String(str).replace(/\{([a-zA-Z0-9_]+)\}/g, function (_, k) {
    return vars.hasOwnProperty(k) ? String(vars[k]) : ('{' + k + '}');
  });
}

function supported() { return SUPPORTED.slice(); }
function isSupported(code) { return SUPPORTED.indexOf(code) >= 0; }

module.exports = {
  t: t,
  load: load,
  setLang: setLang,
  getLang: getLang,
  onChange: onChange,
  supported: supported,
  isSupported: isSupported,
  defaultLang: DEFAULT_LANG,
};
